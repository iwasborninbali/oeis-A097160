/* Complete finite search. No floating point arithmetic in the mathematics.
   gcc -O3 -std=c11 -Wall -Wextra scan.c -o scan
   scan K EXCLUSIVE_UPPER LOWER output.tsv summary.json
   LOWER normally 2; subranges can be combined only after checking coverage. */
#define _POSIX_C_SOURCE 200809L
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <inttypes.h>
#include <string.h>
#include <time.h>
#include <errno.h>
#define SEG (1u<<20)
static uint64_t evaluations;
static int jacobi_plain(uint64_t a,uint64_t b) {
    int s=1;
    while(a) {
        unsigned z=__builtin_ctzll(a);a>>=z;
        if((z&1) && ((b&7)==3 || (b&7)==5))s=-s;
        if((a&b&3)==3)s=-s;
        uint64_t t=b%a;b=a;a=t;
    }
    return b==1?s:0;
}
/* Quadratic reciprocity tables for every odd denominator <=4095.
   Sum_{j=0}^{2047}(2*j+1)=2048^2 entries, about 4 MiB.
   The table is generated by the plain binary algorithm once at startup. */
#define TABHALF 2048u
static int8_t table[TABHALF*TABHALF];
static void initialize_table(void) {
    for(uint64_t j=0;j<TABHALF;j++) {
        uint64_t m=2*j+1;
        for(uint64_t r=0;r<m;r++)table[j*j+r]=(int8_t)jacobi_plain(r,m);
    }
}
static int jacobi(uint64_t a,uint64_t b) {
    int s=1;
    while(a) {
        unsigned z=__builtin_ctzll(a);a>>=z;
        if((z&1) && ((b&7)==3 || (b&7)==5))s=-s;
        if((a&b&3)==3)s=-s;
        uint64_t r=b%a;
        if(a<2*TABHALF) {uint64_t j=a/2;return s*table[j*j+r];}
        b=a;a=r;
    }
    return b==1?s:0;
}
/* Multiplicativity prefilter: each supported a is represented by the
   parity mask of its prime exponents, using all 54 primes <=251.
   This is an exact Legendre evaluation, with direct Jacobi fallback.
   No residue is inferred from a statistical model. */
#define MASK_SIZE (1u<<20)
static uint64_t masks[MASK_SIZE], signature, active_prime;
static uint32_t small_factors[MASK_SIZE], basis[64];
static unsigned basis_count;
static void initialize_masks(void) {
    for(uint32_t q=2;q<MASK_SIZE;q++)if(!small_factors[q]) {
        if(q<=251)basis[basis_count++]=q;
        if(q<=(MASK_SIZE-1)/q)
            for(uint32_t j=q*q;j<MASK_SIZE;j+=q)
                if(!small_factors[j])small_factors[j]=q;
    }
    masks[1]=0;
    for(uint32_t a=2;a<MASK_SIZE;a++) {
        uint32_t q=small_factors[a];if(!q)q=a;
        unsigned i=0;while(i<basis_count && basis[i]!=q)++i;
        if(i==basis_count || masks[a/q]==UINT64_MAX)masks[a]=UINT64_MAX;
        else masks[a]=masks[a/q]^(UINT64_C(1)<<i);
    }
}
static void begin_prime(uint64_t p) {
    active_prime=p;signature=0;
    if(p>251)for(unsigned i=0;i<basis_count;i++)
        if(jacobi(basis[i],p)==-1)signature|=UINT64_C(1)<<i;
}
static int residue(uint64_t a,uint64_t p) {
    evaluations++;
    if(p==active_prime && p>251 && a<MASK_SIZE && masks[a]!=UINT64_MAX)
        return !__builtin_parityll(masks[a]&signature);
    return jacobi(a,p)==1;
}
/* Candidate start s: inspect cheap characters first, from right to left, then the rest. A nonresidue x
   rules out every start from s through x; hence next start is x+1.
   A successful window is the FIRST k-run, despite the order of inspections. */
static uint64_t first_run(uint64_t p,unsigned k) {
    if(p<=k)return 0;
    uint64_t s=1;
    while(s<=p-k) {
        uint64_t end=s+k-1,x=end;
        if(p>251 && end<MASK_SIZE) {
            /* Test the inexpensive exact mask characters first. The first
               obstruction found at x still safely excludes starts s..x. */
            do {
                if(masks[x]!=UINT64_MAX && !residue(x,p))goto blocked;
            }while(x-- > s);
            x=end;
            do {
                if(masks[x]==UINT64_MAX && !residue(x,p))goto blocked;
            }while(x-- > s);
            return s;
        }
        while(residue(x,p)) {if(x==s)return s;--x;}
        blocked: s=x+1;
    }
    return 0;
}
static unsigned longest(uint64_t p,uint64_t *start) {
    unsigned r=0,b=0;*start=0;
    for(uint64_t x=1;x<p;x++) {
        if(residue(x,p)){r++;if(r>b){b=r;*start=x-r+1;}}
        else r=0;
    }
    return b;
}
static double wall(void){struct timespec t;clock_gettime(CLOCK_MONOTONIC,&t);return t.tv_sec+t.tv_nsec*1e-9;}
int main(int argc,char **argv) {
    if(argc!=7){fprintf(stderr,"usage: scan K UPPER LOWER exceptions.tsv summary.json PROGRESS_STEP\n");return 2;}
    unsigned k=strtoul(argv[1],0,10);uint64_t upper=strtoull(argv[2],0,10),lower=strtoull(argv[3],0,10),step=strtoull(argv[6],0,10);
    if(k<2||k>30||lower<2||upper<=lower||upper>UINT64_C(1000000000000))return 2;
    double t0=wall();clock_t c0=clock();initialize_table();initialize_masks();
    uint64_t root=1;while((root+1)<= (upper-1)/(root+1))root++;
    uint8_t *small=calloc(root+1,1),*mark=malloc(SEG);
    uint32_t *primes=malloc((root+1)*sizeof(uint32_t));if(!small||!mark||!primes)return 3;
    size_t np=0;
    for(uint64_t q=2;q<=root;q++)if(!small[q]){
        primes[np++]=(uint32_t)q;
        if(q<=root/q)for(uint64_t j=q*q;j<=root;j+=q)small[j]=1;
    }
    FILE *out=fopen(argv[4],"w");if(!out){perror(argv[4]);return 3;}
    fprintf(out,"# prime longest_run first_maximum_start; k=%u interval=[%"PRIu64",%"PRIu64")\n",k,lower,upper);
    uint64_t count=0,exceptions=0,endpoint=0,maxwitness=0,next=step;
    for(uint64_t lo=lower;lo<upper;lo+=SEG){
        uint64_t hi=lo+SEG;if(hi>upper)hi=upper;
        memset(mark,0,(size_t)(hi-lo));
        for(size_t i=0;i<np;i++){
            uint64_t q=primes[i];if(q*q>=hi)break;
            uint64_t a=((lo+q-1)/q)*q;if(a<q*q)a=q*q;
            for(;a<hi;a+=q)mark[a-lo]=1;
        }
        for(uint64_t p=lo;p<hi;p++)if(!mark[p-lo]){
            ++count;begin_prime(p);uint64_t s=p==2?0:first_run(p,k);
            if(!s){uint64_t a;unsigned m=p==2?1:longest(p,&a);if(p==2)a=1;
                if(m>=k){fprintf(stderr,"INTERNAL contradiction at %"PRIu64"\n",p);return 4;}
                fprintf(out,"%"PRIu64" %u %"PRIu64"\n",p,m,a);++exceptions;if(m==k-1)endpoint=p;
            }else if(s+k-1>maxwitness)maxwitness=s+k-1;
        }
        if(step && hi>=next){fprintf(stderr,"k=%u through=%"PRIu64" primes=%"PRIu64" exceptions=%"PRIu64" wall=%.3f cpu=%.3f\n",k,hi,count,exceptions,wall()-t0,(double)(clock()-c0)/CLOCKS_PER_SEC);fflush(out);next=hi+step;}
    }
    if(fclose(out)){perror("fclose");return 3;}
    FILE *meta=fopen(argv[5],"w");if(!meta)return 3;
    fprintf(meta,"{\"k\":%u,\"lower\":%"PRIu64",\"upper_exclusive\":%"PRIu64",\"prime_count\":%"PRIu64",\"exception_count\":%"PRIu64",\"endpoint\":%"PRIu64",\"largest_first_witness_end\":%"PRIu64",\"jacobi_evaluations\":%"PRIu64",\"wall_seconds\":%.6f,\"cpu_seconds\":%.6f}\n",k,lower,upper,count,exceptions,endpoint,maxwitness,evaluations,wall()-t0,(double)(clock()-c0)/CLOCKS_PER_SEC);
    fclose(meta);free(small);free(mark);free(primes);return 0;
}
